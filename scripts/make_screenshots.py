#!/usr/bin/env python3
"""Render the README's terminal screenshots from live Surveyor output.

Every pixel in ``docs/screenshots/*.png`` comes from a real ``surveyor``
invocation. Nothing is drawn by hand and nothing is pasted from a terminal
that happened to look good: the script drives the CLI, captures the bytes it
writes, and paints those bytes into a window frame.

Usage::

    python3 -m pip install pillow
    python3 scripts/make_screenshots.py            # regenerate every shot
    python3 scripts/make_screenshots.py --redact   # privacy-safe variant
    python3 scripts/make_screenshots.py --keep     # leave the demo ledger behind

The script needs Pillow, which is a *development* dependency only. The
Surveyor itself still has zero runtime dependencies.

What gets captured, and why:

``scan.png``
    A live survey of this machine, with the layered plat and the idempotence
    proof underneath it ("unchanged - HEAD #1 - nothing to record").
``diff.png``
    A real structural diff between two real surveys. The second survey adds
    the workload layer to the first by widening the scanner set, so the diff
    is generated by the same code path that would report a container upgrade.
``changelog.png``
    The scribe's markdown entry for that same diff, template backend, no
    model involved.
``ledger.png``
    ``surveyor log`` and ``surveyor verify``: the journal and the hash chain.

The demo ledger is built in a throwaway directory and removed afterwards
unless ``--keep`` is given. ``--redact`` runs every scan with redaction on,
which masks MAC addresses, serials and public IPv4 addresses.
"""

from __future__ import annotations

import argparse
import os
import re
import subprocess
import sys
import tempfile
from dataclasses import dataclass, replace
from pathlib import Path

try:
    from PIL import Image, ImageDraw, ImageFont
except ImportError:  # pragma: no cover - developer tooling
    raise SystemExit(
        "Pillow is required to render screenshots: python3 -m pip install pillow"
    ) from None

REPO = Path(__file__).resolve().parent.parent
OUTPUT_DIR = REPO / "docs" / "screenshots"

MONO_FONTS = (
    "/System/Library/Fonts/Menlo.ttc",
    "/System/Library/Fonts/Monaco.ttf",
    "/System/Library/Fonts/DejaVuSansMono.ttf",
)
FALLBACK_FONTS = (
    "/System/Library/Fonts/Apple Symbols.ttf",
    "/System/Library/Fonts/Supplemental/Arial Unicode.ttf",
)

FONT_SIZE = 15
LINE_SPACING = 1.45
WINDOW_PADDING = 18
TITLEBAR_HEIGHT = 30

# --------------------------------------------------------------------------
# palette
# --------------------------------------------------------------------------
BACKGROUND = (13, 17, 23)
TITLEBAR = (22, 27, 34)
BORDER = (48, 54, 61)
FOREGROUND = (201, 209, 217)
DIM = (110, 118, 129)
PROMPT = (126, 231, 135)

ANSI_COLORS = {
    30: (72, 79, 88),
    31: (248, 81, 73),
    32: (63, 185, 80),
    33: (210, 153, 34),
    34: (88, 166, 255),
    35: (188, 140, 255),
    36: (57, 197, 207),
    37: (201, 209, 217),
    90: (110, 118, 129),
    91: (255, 123, 114),
    92: (86, 211, 100),
    93: (233, 196, 106),
    94: (121, 192, 255),
    95: (210, 168, 255),
    96: (118, 224, 232),
    97: (240, 246, 252),
}


# --------------------------------------------------------------------------
# ANSI parsing
# --------------------------------------------------------------------------
SGR_RE = re.compile(r"\x1b\[([0-9;]*)m")
#: Every CSI escape that is *not* a colour change (cursor moves, erases).
OTHER_ESC_RE = re.compile(r"\x1b\[[0-9;?]*[A-Za-ln-z]")


@dataclass(frozen=True)
class Cell:
    """One character cell: what to draw, and in what style."""

    ch: str
    fg: tuple[int, int, int] | None = None
    bg: tuple[int, int, int] | None = None
    bold: bool = False
    dim: bool = False


@dataclass(frozen=True)
class Style:
    fg: tuple[int, int, int] | None = None
    bg: tuple[int, int, int] | None = None
    bold: bool = False
    dim: bool = False


def _xterm256(index: int) -> tuple[int, int, int]:
    if index < 16:
        base = [
            (0, 0, 0), (205, 49, 49), (13, 188, 121), (229, 229, 16),
            (36, 114, 200), (188, 63, 188), (17, 168, 205), (229, 229, 229),
            (102, 102, 102), (241, 76, 76), (35, 209, 139), (245, 245, 67),
            (59, 142, 234), (214, 112, 214), (41, 184, 219), (255, 255, 255),
        ]
        return base[index]
    if index < 232:
        index -= 16
        steps = (0, 95, 135, 175, 215, 255)
        return (
            steps[index // 36],
            steps[(index // 6) % 6],
            steps[index % 6],
        )
    grey = 8 + (index - 232) * 10
    return (grey, grey, grey)


def _apply_sgr(style: Style, codes: list[int]) -> Style:
    index = 0
    while index < len(codes):
        code = codes[index]
        if code == 0:
            style = Style()
        elif code == 1:
            style = replace(style, bold=True)
        elif code == 2:
            style = replace(style, dim=True)
        elif code == 22:
            style = replace(style, bold=False, dim=False)
        elif code == 39:
            style = replace(style, fg=None)
        elif code == 49:
            style = replace(style, bg=None)
        elif code in ANSI_COLORS:
            style = replace(style, fg=ANSI_COLORS[code])
        elif 40 <= code <= 47:
            style = replace(style, bg=ANSI_COLORS[code - 10])
        elif 100 <= code <= 107:
            style = replace(style, bg=ANSI_COLORS[code - 10 + 60])
        elif code in (38, 48):
            if index + 2 < len(codes) and codes[index + 1] == 5:
                colour = _xterm256(codes[index + 2])
                index += 2
            elif index + 4 < len(codes) and codes[index + 1] == 2:
                colour = (codes[index + 2], codes[index + 3], codes[index + 4])
                index += 4
            else:
                index += 1
                continue
            style = replace(style, fg=colour if code == 38 else style.fg)
            if code == 48:
                style = replace(style, bg=colour)
        index += 1
    return style


def _emit(lines: list[list[Cell]], chunk: str, style: Style) -> None:
    for index, raw_line in enumerate(chunk.split("\n")):
        if index:
            lines.append([])
        if raw_line:
            lines[-1].extend(
                Cell(ch, style.fg, style.bg, style.bold, style.dim) for ch in raw_line
            )


def parse_ansi(text: str) -> list[list[Cell]]:
    """Turn ANSI-coloured text into a grid of styled cells."""

    text = OTHER_ESC_RE.sub("", text)
    lines: list[list[Cell]] = [[]]
    style = Style()
    position = 0
    for match in SGR_RE.finditer(text):
        _emit(lines, text[position : match.start()], style)
        raw = match.group(1)
        parts = raw.split(";") if raw else ["0"]
        style = _apply_sgr(style, [int(part) if part else 0 for part in parts])
        position = match.end()
    _emit(lines, text[position:], style)
    while lines and not lines[-1]:
        lines.pop()
    return lines


# --------------------------------------------------------------------------
# fonts
# --------------------------------------------------------------------------
class FontBook:
    """Menlo plus a fallback chain, because one glyph is in nobody's font."""

    def __init__(self) -> None:
        self.regular: ImageFont.FreeTypeFont | None = None
        self.bold: ImageFont.FreeTypeFont | None = None
        self.title: ImageFont.FreeTypeFont | None = None
        for candidate in MONO_FONTS:
            if Path(candidate).exists():
                self.regular = ImageFont.truetype(candidate, FONT_SIZE, index=0)
                try:
                    self.bold = ImageFont.truetype(candidate, FONT_SIZE, index=1)
                except (OSError, ValueError):
                    self.bold = self.regular
                try:
                    self.title = ImageFont.truetype(candidate, 12, index=0)
                except (OSError, ValueError):
                    self.title = self.regular
                break
        if self.regular is None:  # pragma: no cover - depends on the host
            raise SystemExit("no monospace font found; install DejaVu Sans Mono")
        self.fallbacks: list[ImageFont.FreeTypeFont] = []
        for candidate in FALLBACK_FONTS:
            if Path(candidate).exists():
                self.fallbacks.append(ImageFont.truetype(candidate, FONT_SIZE, index=0))
        self._missing = self._notdef_signature(self.regular)
        self._cache: dict[str, ImageFont.FreeTypeFont] = {}

    @staticmethod
    def _notdef_signature(font: ImageFont.FreeTypeFont) -> bytes:
        canvas = Image.new("L", (32, 32), 0)
        ImageDraw.Draw(canvas).text((2, 2), "\ue123", font=font, fill=255)
        return canvas.tobytes()

    def _signature(self, font: ImageFont.FreeTypeFont, ch: str) -> bytes:
        canvas = Image.new("L", (32, 32), 0)
        ImageDraw.Draw(canvas).text((2, 2), ch, font=font, fill=255)
        return canvas.tobytes()

    def font_for(self, ch: str, bold: bool) -> ImageFont.FreeTypeFont:
        key = f"{ch}\x00{int(bold)}"
        cached = self._cache.get(key)
        if cached is not None:
            return cached
        base = self.bold if bold and self.bold is not None else self.regular
        chosen = base
        if self._signature(base, ch) == self._missing:
            for fallback in self.fallbacks:
                if self._signature(fallback, ch) != self._missing:
                    chosen = fallback
                    break
        self._cache[key] = chosen
        return chosen

    @property
    def cell_width(self) -> int:
        return round(self.regular.getlength("M"))

    @property
    def line_height(self) -> int:
        ascent, descent = self.regular.getmetrics()
        return round((ascent + descent) * LINE_SPACING)


# --------------------------------------------------------------------------
# rendering
# --------------------------------------------------------------------------
def _blend(colour: tuple[int, int, int], background: tuple[int, int, int], alpha: float) -> tuple[int, int, int]:
    return tuple(
        round(b + (c - b) * alpha) for c, b in zip(colour, background, strict=True)
    )


def render_window(rows: list[list[Cell]], title: str, fonts: FontBook) -> Image.Image:
    """Paint a terminal session into a window frame."""

    columns = max((len(row) for row in rows), default=1)
    cell_w = fonts.cell_width
    line_h = fonts.line_height

    width = columns * cell_w + WINDOW_PADDING * 2
    height = len(rows) * line_h + WINDOW_PADDING * 2 + TITLEBAR_HEIGHT

    image = Image.new("RGB", (width, height), BACKGROUND)
    draw = ImageDraw.Draw(image)

    # title bar
    draw.rectangle([0, 0, width, TITLEBAR_HEIGHT], fill=TITLEBAR)
    radius = 6
    for offset, colour in enumerate(((255, 95, 87), (254, 188, 46), (39, 200, 64))):
        cx = 18 + offset * 20
        draw.ellipse([cx - radius, TITLEBAR_HEIGHT // 2 - radius, cx + radius, TITLEBAR_HEIGHT // 2 + radius], fill=colour)
    title_font = fonts.title or fonts.regular
    try:
        title_width = draw.textlength(title, font=title_font)
    except AttributeError:  # pragma: no cover - very old Pillow
        title_width = fonts.regular.getlength(title)
    draw.text(
        ((width - title_width) / 2, TITLEBAR_HEIGHT / 2 - 7),
        title,
        font=title_font,
        fill=(139, 148, 158),
    )
    draw.line([(0, TITLEBAR_HEIGHT), (width, TITLEBAR_HEIGHT)], fill=BORDER)

    # content
    baseline_offset = TITLEBAR_HEIGHT + WINDOW_PADDING
    for row_index, row in enumerate(rows):
        y = baseline_offset + row_index * line_h
        for column_index, cell in enumerate(row):
            x = WINDOW_PADDING + column_index * cell_w
            if cell.bg is not None:
                draw.rectangle([x, y, x + cell_w, y + line_h], fill=cell.bg)
            colour = cell.fg or FOREGROUND
            if cell.dim:
                colour = _blend(colour, BACKGROUND, 0.55)
            draw.text((x, y + 2), cell.ch, font=fonts.font_for(cell.ch, cell.bold), fill=colour)

    # rounded corners and border
    mask = Image.new("L", (width, height), 0)
    ImageDraw.Draw(mask).rounded_rectangle([0, 0, width - 1, height - 1], radius=10, fill=255)
    rounded = Image.new("RGB", (width, height), BACKGROUND)
    rounded.paste(image, (0, 0), mask)
    ImageDraw.Draw(rounded).rounded_rectangle([0, 0, width - 1, height - 1], radius=10, outline=BORDER)
    return rounded


# --------------------------------------------------------------------------
# terminal session assembly
# --------------------------------------------------------------------------
def prompt_line(command: str) -> list[Cell]:
    """`$ command`, styled the way a shell would style it."""

    return [Cell("$", PROMPT, None, True)] + [
        Cell(" " + chunk, FOREGROUND, None, False)
        for chunk in [command]
    ]


def session(title: str, blocks: list[tuple[str, str]], fonts: FontBook) -> Image.Image:
    """Build a window from a list of (command, output) pairs."""

    rows: list[list[Cell]] = []
    for index, (command, output) in enumerate(blocks):
        if index:
            rows.append([])
        rows.append(prompt_line(command))
        if output:
            rows.extend(parse_ansi(output.rstrip("\n")))
    return render_window(rows, title, fonts)


# --------------------------------------------------------------------------
# driving the CLI
# --------------------------------------------------------------------------
def run_cli(args: list[str], cwd: Path, redact: bool) -> str:
    """Run the real CLI and return exactly what it printed."""

    env = dict(os.environ)
    env["PYTHONPATH"] = str(REPO / "src")
    env["FORCE_COLOR"] = "1"
    env["COLUMNS"] = "240"
    env.pop("NO_COLOR", None)
    if redact:
        env["SURVEYOR_REDACT"] = "true"
    completed = subprocess.run(
        [sys.executable, "-m", "surveyor", *args],
        cwd=str(cwd),
        env=env,
        capture_output=True,
        text=True,
        check=False,
    )
    return completed.stdout + completed.stderr


def survey(cwd: Path, redact: bool, scanners: str | None = None, ascii_map: bool = False) -> str:
    args = ["--store", ".ledger", "--site", "edge", "scan"]
    if scanners:
        args += ["--scanners", scanners]
    if ascii_map:
        args += ["--ascii"]
    return run_cli(args, cwd, redact)


# --------------------------------------------------------------------------
# main
# --------------------------------------------------------------------------
def build(redact: bool, keep: bool) -> int:
    fonts = FontBook()
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)

    with tempfile.TemporaryDirectory(prefix="surveyor-shots-") as raw:
        work = Path(raw)
        store = work / ".ledger"

        # 1. Baseline: the box, its power and its cabling, but no workloads.
        survey(work, redact, scanners="host,network,power")
        # 2. The workload layer comes online. This is a real structural change.
        survey(work, redact)

        written: list[Path] = []

        # -- scan.png -----------------------------------------------------
        scan_output = survey(work, redact, ascii_map=True)
        shot = session(
            "edge — surveyor scan",
            [("surveyor scan --ascii", scan_output)],
            fonts,
        )
        path = OUTPUT_DIR / "scan.png"
        shot.save(path, optimize=True)
        written.append(path)

        # -- diff.png -----------------------------------------------------
        diff_output = run_cli(
            ["--store", ".ledger", "diff", "--from", "HEAD~1", "--to", "HEAD"], work, redact
        )
        shot = session(
            "edge — surveyor diff",
            [("surveyor diff --from HEAD~1 --to HEAD", diff_output)],
            fonts,
        )
        path = OUTPUT_DIR / "diff.png"
        shot.save(path, optimize=True)
        written.append(path)

        # -- changelog.png -------------------------------------------------
        changelog_output = run_cli(
            ["--store", ".ledger", "diff", "--format", "markdown"], work, redact
        )
        shot = session(
            "edge — surveyor diff --format markdown",
            [("surveyor diff --format markdown", changelog_output)],
            fonts,
        )
        path = OUTPUT_DIR / "changelog.png"
        shot.save(path, optimize=True)
        written.append(path)

        # -- ledger.png ---------------------------------------------------
        log_output = run_cli(["--store", ".ledger", "log"], work, redact)
        verify_output = run_cli(["--store", ".ledger", "verify"], work, redact)
        shot = session(
            "edge — surveyor log && surveyor verify",
            [
                ("surveyor log", log_output),
                ("surveyor verify", verify_output),
            ],
            fonts,
        )
        path = OUTPUT_DIR / "ledger.png"
        shot.save(path, optimize=True)
        written.append(path)

        if keep:
            destination = REPO / "docs" / ".demo-ledger"
            if destination.exists():
                import shutil

                shutil.rmtree(destination)
            destination.parent.mkdir(parents=True, exist_ok=True)
            import shutil

            shutil.copytree(store, destination)
            print(f"kept demo ledger at {destination}")

    for path in written:
        size = path.stat().st_size
        print(f"wrote {path.relative_to(REPO)} · {size // 1024} KiB")
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--redact", action="store_true", help="mask identifiers in every capture")
    parser.add_argument("--keep", action="store_true", help="keep the demo ledger in docs/.demo-ledger")
    args = parser.parse_args(argv)
    return build(args.redact, args.keep)


if __name__ == "__main__":
    raise SystemExit(main())
