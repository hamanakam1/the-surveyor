"""The conformance suite: every rule, one broken document at a time.

A validator is only as good as the things it rejects. The corpus in
``tests/fixtures/invalid`` holds one document per rule, each broken in
exactly one way, and the file name says which way. If a rule stops being
enforced, this suite fails.

The committed corpus is generated by ``scripts/make_conformance.py``; a test
asserts the committed files are exactly what the script produces.
"""

from __future__ import annotations

import json
from pathlib import Path

import pytest

from surveyor.model import KINDS, LAYERS, RELATIONS, Edge, Node, Topology
from surveyor.validation import Problem, codes, validate_document, validate_topology

ROOT = Path(__file__).resolve().parents[1]
CASES = ROOT / "tests" / "fixtures" / "invalid"


def _cases() -> list[tuple[str, dict]]:
    found = []
    for path in sorted(CASES.glob("*.json")):
        found.append((path.stem.split("__", 1)[0], json.loads(path.read_text(encoding="utf-8"))))
    return found


def test_the_conformance_corpus_is_not_empty():
    assert len(list(CASES.glob("*.json"))) >= 20


@pytest.mark.parametrize(
    ("expected", "document"),
    _cases(),
    ids=[name for name, _ in _cases()],
)
def test_each_broken_document_is_rejected_for_its_own_reason(expected, document):
    problems = validate_document(document)
    assert problems, "a broken document must be rejected"
    assert expected in codes(problems), (
        f"expected {expected!r}, got {codes(problems)}"
    )


def test_the_committed_corpus_matches_the_generator():
    """The corpus is generated, so it cannot drift from the generator."""

    import importlib.util

    spec = importlib.util.spec_from_file_location(
        "make_conformance", ROOT / "scripts" / "make_conformance.py"
    )
    module = importlib.util.module_from_spec(spec)
    assert spec.loader is not None
    spec.loader.exec_module(module)

    for name, build in module.CASES.items():
        path = CASES / f"{name}.json"
        assert path.exists(), f"{name} is missing from the corpus"
        committed = json.loads(path.read_text(encoding="utf-8"))
        assert committed == build(), f"{name} does not match the generator"


def test_the_committed_schema_matches_the_generator():
    """The schema is generated from the model, so it cannot drift away.

    This guard lives here rather than in the documentation tests because it
    is a statement about the contract, not about the prose.
    """

    import importlib.util

    spec = importlib.util.spec_from_file_location(
        "make_schema", ROOT / "scripts" / "make_schema.py"
    )
    module = importlib.util.module_from_spec(spec)
    assert spec.loader is not None
    spec.loader.exec_module(module)
    committed = (ROOT / "schema" / "oet-1.0.schema.json").read_text(encoding="utf-8")
    assert committed == module.render(), (
        "schema/oet-1.0.schema.json is stale; run `make schema`"
    )


