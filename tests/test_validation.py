"""The conformance suite: every rule, one broken document at a time.

A validator is only as good as the things it rejects. The corpus in
``tests/fixtures/invalid`` holds one document per rule, each broken in
exactly one way, and the file name says which way. If a rule stops being
enforced, this suite fails.

The committed corpus is generated by ``scripts/make_conformance.py``; a test
asserts the committed files are exactly what the script produces.
"""

from __future__ import annotations

import json
from pathlib import Path

import pytest

from surveyor.model import KINDS, LAYERS, RELATIONS, Topology
from surveyor.validation import Problem, codes, validate_document, validate_topology

ROOT = Path(__file__).resolve().parents[1]
CASES = ROOT / "tests" / "fixtures" / "invalid"


def _cases() -> list[tuple[str, dict]]:
    found = []
    for path in sorted(CASES.glob("*.json")):
        found.append((path.stem.split("__", 1)[0], json.loads(path.read_text(encoding="utf-8"))))
    return found


def test_the_conformance_corpus_is_not_empty():
    assert len(list(CASES.glob("*.json"))) >= 20


@pytest.mark.parametrize(
    "expected,document",
    _cases(),
    ids=[name for name, _ in _cases()],
)
def test_each_broken_document_is_rejected_for_its_own_reason(expected, document):
    problems = validate_document(document)
    assert problems, "a broken document must be rejected"
    assert expected in codes(problems), (
        f"expected {expected!r}, got {codes(problems)}"
    )


def test_the_committed_corpus_matches_the_generator():
    """The corpus is generated, so it cannot drift from the generator."""

    import importlib.util

    spec = importlib.util.spec_from_file_location(
        "make_conformance", ROOT / "scripts" / "make_conformance.py"
    )
    module = importlib.util.module_from_spec(spec)
    assert spec.loader is not None
    spec.loader.exec_module(module)

    for name, build in module.CASES.items():
        path = CASES / f"{name}.json"
        assert path.exists(), f"{name} is missing from the corpus"
        committed = json.loads(path.read_text(encoding="utf-8"))
        assert committed == build(), f"{name} does not match the generator"


def test_a_good_plat_has_no_problems(topology):
    document = topology.to_dict()
    assert validate_document(document) == []
    assert validate_topology(topology) == []


def test_the_bundled_sample_is_valid():
    document = json.loads((ROOT / "examples" / "sample.oet.json").read_text(encoding="utf-8"))
    assert validate_document(document) == []


def test_a_plat_with_an_unknown_minor_is_still_accepted(topology):
    """Consumers reject an unknown major and may accept an unknown minor."""

    document = topology.to_dict()
    document["oet_version"] = "1.7"
    assert validate_document(document) == []


def test_a_plat_with_an_unknown_major_is_rejected(topology):
    document = topology.to_dict()
    document["oet_version"] = "2.0"
    assert "unknown-version" in codes(validate_document(document))


def test_the_validator_agrees_with_the_model(topology):
    """A kind the model knows and the validator does not would be a hole."""

    document = topology.to_dict()
    for kind in KINDS:
        document["nodes"][0]["kind"] = kind
        assert "unknown-kind" not in codes(validate_document(document))
    for layer in LAYERS:
        document["nodes"][0]["layer"] = layer
        assert "unknown-layer" not in codes(validate_document(document))
    for relation in RELATIONS:
        document["edges"][0]["relation"] = relation
        assert "unknown-relation" not in codes(validate_document(document))


def test_the_fingerprint_mismatch_is_reported(topology):
    document = topology.to_dict()
    document["fingerprint"] = "sha256:" + "0" * 64
    assert "fingerprint-mismatch" in codes(
        validate_topology(Topology.from_dict(document), document)
    )


def test_every_problem_carries_a_path_and_a_message():
    problems = validate_document({"oet_version": "1.0"})
    assert problems
    for problem in problems:
        assert isinstance(problem, Problem)
        assert problem.path
        assert problem.message
        assert problem.to_dict()["code"] == problem.code
